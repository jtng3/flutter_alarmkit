#if !targetEnvironment(macCatalyst)
@available(iOS 26.0, *)
struct OpenAlarmAppIntent: LiveActivityIntent {
  static let title: LocalizedStringResource = "Open"
  static let description = IntentDescription("Stop the alarm and open the app")
  static let supportedModes: IntentModes = .foreground(.immediate)

  @Parameter(title: "alarmID")
  var alarmID: String

  init() { alarmID = "" }
  init(alarmID: String) { self.alarmID = alarmID }

  func perform() async throws -> some IntentResult {
    UserDefaults.standard.set(alarmID, forKey: FlutterAlarmkitIntents.lastOpenedAlarmKey)
    if let id = UUID(uuidString: alarmID) {
      try? AlarmManager.shared.stop(id: id)
    }
    return .result()
  }
}
#endif
// flutter_alarmkit:open-app-intent:end
