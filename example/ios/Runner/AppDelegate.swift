import AppIntents
import AlarmKit
import flutter_alarmkit
import Flutter
import UIKit

@main
@objc class AppDelegate: FlutterAppDelegate, FlutterImplicitEngineDelegate {
  override func application(
    _ application: UIApplication,
    didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?
  ) -> Bool {
    #if !targetEnvironment(macCatalyst)
    if #available(iOS 26.0, *) {
      FlutterAlarmkitIntents.openAppIntentFactory = { OpenAlarmAppIntent(alarmID: $0) }
    }
    #endif
    return super.application(application, didFinishLaunchingWithOptions: launchOptions)
  }

  func didInitializeImplicitFlutterEngine(_ engineBridge: FlutterImplicitEngineBridge) {
    GeneratedPluginRegistrant.register(with: engineBridge.pluginRegistry)
  }
}

// flutter_alarmkit:open-app-intent:begin
// Generated by `dart run flutter_alarmkit:setup`. Do not edit; re-run setup.
#if !targetEnvironment(macCatalyst)
@available(iOS 26.0, *)
struct OpenAlarmAppIntent: LiveActivityIntent {
  static let title: LocalizedStringResource = "Open"
  static let description = IntentDescription("Stop the alarm and open the app")
  static let supportedModes: IntentModes = .foreground(.immediate)

  @Parameter(title: "alarmID")
  var alarmID: String

  init() { alarmID = "" }
  init(alarmID: String) { self.alarmID = alarmID }

  func perform() async throws -> some IntentResult {
    // The system stops and removes the alarm before running this intent
    // (observed on iOS 26.7.1: alarmUpdates reports alerting -> removed, then
    // the intent runs; AlarmManager.stop here throws Code=0). So only record
    // which alarm opened the app and let the app foreground.
    UserDefaults.standard.set(alarmID, forKey: FlutterAlarmkitIntents.lastOpenedAlarmKey)
    return .result()
  }
}
#endif
// flutter_alarmkit:open-app-intent:end
